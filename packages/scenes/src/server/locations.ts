const searchable = (value: string) => value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLocaleLowerCase('en');
export function searchSceneLocations(input: unknown): { locations: SceneLocation[] } {
  if (typeof input !== 'string' || input.trim().length < 2 || input.trim().length > 120 || /[\u0000-\u001f\u007f]/.test(input)) throw new SceneError(400, 'Enter a city name between 2 and 120 characters.');
  const query = searchable(input.trim());
  return { locations: SCENE_LOCATIONS.filter(location => searchable(location.name).includes(query) || searchable(location.timeZone).includes(query)).slice(0, 8) };
}
