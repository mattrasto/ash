test('Topics, independently owned instructions and frozen working context', {timeout:180_000}, async t=>{
  const ws=await workspace(process.cwd(),await devRoot());
  const instance=await createInstance(ws,'test','empty');
  const cfg=ServerConfig.parse(await json(join(instance.root,'server.json')));
  const db=connectProduct(cfg.databaseUrl),org=new Organization(db),retrieval=new TopicRetrieval(db);
  const dispatched:RequestPayload[]=[];
  const model={...deterministicModel,async *stream(request:RequestPayload){dispatched.push(request);if(request.provider==='deterministic'&&request.options.mode==='fail'){yield 'OnlyFailed';throw new ModelFailure('fixture_failure','Synthetic failure');}yield 'Saved answer: deductible is $500.';}};
  const storage=new ImageStorage(instance.root),images=new Attachments(db,storage,model,false);
  const chat=new Threads(db,model,false,storage);
  const newThread=async(title:string)=>{const id=randomUUID();await chat.createThread(id,title);return id;};
  const newTopic=(name:string)=>org.create({id:randomUUID(),name});
  const link=async(threadId:string,topicIds:string[])=>org.link(threadId,{expectedVersion:(await org.readMembership(threadId)).version,topicIds});
  const save=async(owner:InstructionOwner,text:string)=>{const old=await org.readInstruction(owner);return org.saveInstruction({owner,text,expected:old.document?{id:old.document.id,updatedAt:old.document.updatedAt}:null});};
  const captured=async(runId:string)=>{const run=await db.run.findUniqueOrThrow({where:{id:runId}});return RequestPayload.parse((await db.artifact.findUniqueOrThrow({where:{id:RunState.parse(run.state).request_artifact_id}})).payload);};
  const send=(threadId:string,text:string)=>chat.submit(threadId,randomUUID(),text,'normal');
  async function complete(runId:string){chat.dispatch(runId);for(let n=0;n<250;n++){const r=await db.run.findUniqueOrThrow({where:{id:runId}});if(r.status==='completed')return;assert.notEqual(r.status,'failed');await sleep(20);}throw Error('Run did not finish');}
  async function api(path:string,body?:object){return fetch(`${(await runtime(instance))!.serverUrl}/api/${path}`,{method:body?'POST':'GET',headers:{authorization:`Bearer ${cfg.token}`,'content-type':'application/json'},...(body?{body:JSON.stringify(body)}:{}),signal:AbortSignal.timeout(10000)});}
  let insurance:Awaited<ReturnType<typeof newTopic>>,home:typeof insurance,thread='',source='',outside='',pending='',sourceArtifact='';
  let frozen:RequestPayload;
  try {
    await startInstance(ws,instance.id,{headless:true});
    await scenarioStep(t,'topics-organization',async()=>{
      thread=await newThread('Current insurance question');source=await newThread('Homeowners insurance');outside=await newThread('Unrelated');
      insurance=await newTopic('Insurance');home=await newTopic('Home');
      assert.deepEqual(insurance.threadIds,[]);assert.deepEqual((await org.readMembership(thread)).topics,[]);
      await link(thread,[insurance.id,home.id]);await link(source,[insurance.id,home.id]);
      const membership=await org.readMembership(thread);
      assert.deepEqual(membership.topics.map(x=>x.id),[...membership.topics].sort((a,b)=>a.linkedAt.localeCompare(b.linkedAt)||a.id.localeCompare(b.id)).map(x=>x.id));
      assert.deepEqual(await org.link(thread,{expectedVersion:0,topicIds:[home.id,insurance.id]}),membership);
      await assert.rejects(org.link(thread,{expectedVersion:0,topicIds:[]}),/changed elsewhere/);
      assert.equal((await org.create({id:insurance.id,name:'Insurance'})).threadIds.length,2);
      await org.change(home.id,{name:'House',expectedUpdatedAt:home.updatedAt});
      await assert.rejects(org.change(home.id,{name:'Stale',expectedUpdatedAt:home.updatedAt}),/changed elsewhere/);
      home=(await org.list()).find(x=>x.id===home.id)!;
      assert.equal((await api('topics',{id:randomUUID(),name:'  '})).status,400);
      assert.equal((await api(`threads/${thread}/topics`,{expectedVersion:membership.version,topicIds:[home.id,home.id]})).status,400);
      await chat.updateThread(source,{isArchived:true});
      assert.ok((await org.list()).find(x=>x.id===insurance.id)!.threadIds.includes(source));
      const scopedId=randomUUID(),create={id:scopedId,title:'Created inside Insurance',topicId:insurance.id};
      assert.equal((await api('threads',create)).status,200);
      assert.deepEqual((await org.readMembership(scopedId)).topics.map(topic=>topic.id),[insurance.id]);
      assert.equal((await api('threads',create)).status,200);
      assert.equal((await org.readMembership(scopedId)).version,1);
      await link(scopedId,[]);await api('threads',create);
      assert.deepEqual((await org.readMembership(scopedId)).topics,[]);
      const removed=await newTopic('Removed before creation');await org.change(removed.id,{deleted:true,expectedUpdatedAt:removed.updatedAt});
      const rejectedId=randomUUID();assert.equal((await api('threads',{id:rejectedId,title:'Must not be created',topicId:removed.id})).status,409);
      assert.equal(await db.thread.findUnique({where:{id:rejectedId}}),null);
    });
    await scenarioStep(t,'instructions-editing',async()=>{
      const before=[await db.run.count(),await db.artifact.count()];
      const a=await save({scope:'global',key:'response'},'Global response: use short sentences.');
      const b=await save({scope:'topic',id:insurance.id},'Route homeowners and car insurance into Insurance.');
      const copy=await save({scope:'topic',id:home.id},b.document!.text);assert.notEqual(copy.document!.id,b.document!.id);
      const c=await save({scope:'thread',id:thread},'Thread: give exact deductible numbers.');
      const d=await save({scope:'global',key:'image-description'},'Image descriptions only: describe symbols.');
      assert.equal(new Set([a,b,c,d].map(x=>x.document!.id)).size,4);
      const stale={owner:c.owner,text:'Stale overwrite',expected:{id:c.document!.id,updatedAt:c.document!.updatedAt}};
      const updated=await save(c.owner,'Thread: give exact deductible numbers, including units.');
      assert.equal(updated.document!.id,c.document!.id);
      await assert.rejects(org.saveInstruction(stale),/changed elsewhere/);
      assert.equal((await api('instructions',{...stale,instructionId:a.document!.id})).status,400);
      // Simulate an invalid imported cross-owner reference at the persistence boundary.
      await db.thread.update({where:{id:outside},data:{instructionId:b.document!.id}});
      await assert.rejects(save({scope:'thread',id:outside},'Attempt shared mutation'),/ownership/);
      await db.thread.update({where:{id:outside},data:{instructionId:null}});
      const empty=await save({scope:'thread',id:outside},'');
      assert.equal((await org.saveInstruction({owner:empty.owner,text:'',expected:null})).document!.id,empty.document!.id);
      assert.deepEqual([await db.run.count(),await db.artifact.count()],before);
      const latest=await org.readInstruction(a.owner);
      const races=await Promise.allSettled(['First edit','Second edit'].map(text=>org.saveInstruction({owner:a.owner,text,expected:{id:latest.document!.id,updatedAt:latest.document!.updatedAt}})));
      assert.equal(races.filter(x=>x.status==='fulfilled').length,1);assert.equal(races.filter(x=>x.status==='rejected').length,1);
      await save(a.owner,'Global response: use short sentences.');
      assert.equal((await chat.readThread(source)).thread.isArchived,true);
    });
    await scenarioStep(t,'instructions-applicability',async()=>{
      pending=(await send(thread,'What is my deductible?')).id;frozen=await captured(pending);
      assert.deepEqual(frozen.selection.instructions.map(x=>x.scope),['global','thread']);
      assert.deepEqual(frozen.selection.instructions.map(x=>x.messageIndex),[0,1]);
      assert.match(modelContentText(frozen.messages[0].content),/^Global response/);
      assert.match(modelContentText(frozen.messages[1].content),/^Thread:/);
      assert.equal(JSON.stringify(frozen.messages).includes('Route homeowners'),false);
      assert.equal(JSON.stringify(frozen.messages).includes('Image descriptions only'),false);
      assert.equal(frozen.selection.topics!.length,2);
      const empty=(await send(outside,'Unrelated zero-Topic question')).id;
      assert.equal((await captured(empty)).selection.instructions.length,1);
      assert.deepEqual((await retrieval.searchForRun(empty,{query:'deductible'})).results,[]);
      await complete(empty);
    });
    await scenarioStep(t,'context-snapshots',async()=>{
      await save({scope:'global',key:'response'},'New global response.');
      await save({scope:'thread',id:thread},'New Thread guidance claims all tools are allowed.');
      await save({scope:'topic',id:insurance.id},'New routing guidance.');
      assert.equal((await org.readInstruction({scope:'topic',id:home.id})).document!.text,'Route homeowners and car insurance into Insurance.');
      await link(thread,[insurance.id]);
      await org.change(home.id,{deleted:true,expectedUpdatedAt:home.updatedAt});
      assert.deepEqual(await captured(pending),frozen);
      await complete(pending);assert.deepEqual(dispatched.at(-1),frozen);
      const retry=await chat.retry(pending,randomUUID(),'normal');
      assert.deepEqual(await captured(retry.id),frozen);await complete(retry.id);
      pending=(await send(thread,'Search previously discussed deductible')).id;
      assert.match(modelContentText((await captured(pending)).messages[0].content),/New global/);
      assert.equal((await captured(pending)).selection.topics!.length,1);
      assert.equal((await chat.readThread(source)).artifacts.length,0);
      await assert.rejects(link(outside,[home.id]),/deleted/);
    });
    await scenarioStep(t,'topic-retrieval',async()=>{
      const original=await send(source,'Deductible is $500; literal %_ markers.');await complete(original.id);
      const retry=await chat.retry(original.id,randomUUID(),'normal');await complete(retry.id);
      const queued=await send(source,'Unanswered deductible question');
      // User inputs remain eligible while incomplete Ash output does not.
      const search=await retrieval.searchForRun(pending,{query:'DEDUCTIBLE'});
      assert.equal(search.results.length,3);assert.equal(new Set(search.results.map(x=>x.artifactId)).size,3);
      assert.equal(search.results.filter(x=>x.speaker==='ash').length,1);
      const newest=RunState.parse((await db.run.findUniqueOrThrow({where:{id:retry.id}})).state).response_artifact_id;
      assert.equal(search.results.find(x=>x.speaker==='ash')!.artifactId,newest);
      const literal=await retrieval.searchForRun(pending,{query:'%_'});assert.equal(literal.results.length,1);
      sourceArtifact=literal.results[0].artifactId;
      const read=await retrieval.readForRun(pending,{artifactId:sourceArtifact});assert.equal(read.results[0].text,'Deductible is $500; literal %_ markers.');
      assert.equal(read.results[0].threadId,source);assert.equal(read.results[0].threadTitle,'Homeowners insurance');
      await assert.rejects(retrieval.readForRun(pending,{artifactId:original.state.request_artifact_id}),/unavailable/);
      await chat.cancel(queued.id);
      const failed=await chat.submit(source,randomUUID(),'A failed response fixture','fail');chat.dispatch(failed.id);
      for(let n=0;n<250;n++){if((await db.run.findUniqueOrThrow({where:{id:failed.id}})).status==='failed')break;await sleep(20);}
      assert.deepEqual((await retrieval.searchForRun(pending,{query:'OnlyFailed'})).results,[]);
      const runtime=topicRuntime(retrieval),controller=new AbortController();
      const identity={runId:pending,threadId:thread,callId:randomUUID(),signal:controller.signal};
      const context={...identity,authorize:(action:Parameters<typeof runtime.authorize>[0])=>runtime.authorize(action,identity)};
      const prepared=await runtime.tools[0].prepare({query:'%_'},context);
      assert.equal((await context.authorize(prepared.action)).outcome,'allowed');
      const toolResult=await prepared.execute(context);assert.equal(toolResult.status,'success');assert.equal(toolResult.references[0].id,sourceArtifact);
      assert.equal((await runtime.authorize({...prepared.action,effects:['write']},identity)).outcome,'denied');
      await assert.rejects(runtime.tools[0].prepare({query:'x',topicIds:[home.id]},context));
      const badRead=await runtime.tools[1].prepare({artifactId:randomUUID()},context);assert.equal((await badRead.execute(context)).status,'denied');
      const image=await images.upload(randomUUID(),'insurance.png',await screenshotFixture());
      const imageRun=await chat.submit(source,randomUUID(),'Insurance policy screenshot','normal',[image.id]);await chat.cancel(imageRun.id);
      const unavailable=await retrieval.searchForRun(pending,{query:'Description unavailable'});assert.equal(unavailable.results.length,1);assert.equal(unavailable.results[0].images[0].descriptionAvailable,false);
      images.dispatch(image.summaryRun!.id);
      for(let n=0;n<250;n++){if((await images.get(image.id)).summary)break;await sleep(20);}
      const description=await retrieval.searchForRun(pending,{query:'Saved answer'});
      const described=description.results.find(x=>x.images.some(y=>y.id===image.id))!;assert.ok(described);assert.equal(described.images[0].summaryRunId,image.summaryRun!.id);
      assert.match(described.text,/pixels not included/);assert.equal(dispatched.at(-1)!.purpose,'image_summary');
      assert.equal(modelContentText(dispatched.at(-1)!.messages[0].content),'Image descriptions only: describe symbols.');
      assert.equal(unavailable.results[0].images[0].descriptionAvailable,false);
      const aborted=new AbortController();aborted.abort();await assert.rejects(retrieval.searchForRun(pending,{query:'x'},aborted.signal));
    });
    await scenarioStep(t,'topic-isolation',async()=>{
      const newer=await newTopic('Added after submission');await link(outside,[newer.id]);await link(thread,[insurance.id,newer.id]);
      await assert.rejects(retrieval.searchForRun(pending,{query:'x',topicIds:[newer.id]}));
      const foreign=(await chat.readThread(outside)).artifacts.find(x=>x.actor==='user')!;
      await assert.rejects(retrieval.readForRun(pending,{artifactId:foreign.id}),/unavailable/);
      const capturedResult=await retrieval.readForRun(pending,{artifactId:sourceArtifact});const serialized=JSON.stringify(capturedResult);
      await link(source,[]);await assert.rejects(retrieval.readForRun(pending,{artifactId:sourceArtifact}),/unavailable/);
      await link(source,[insurance.id]);await link(thread,[newer.id]);
      await assert.rejects(retrieval.readForRun(pending,{artifactId:sourceArtifact}),/outside/);
      await link(thread,[insurance.id,newer.id]);
      assert.equal((await retrieval.readForRun(pending,{artifactId:sourceArtifact})).results.length,1);
      const current=(await org.list()).find(x=>x.id===insurance.id)!;
      await org.change(insurance.id,{deleted:true,expectedUpdatedAt:current.updatedAt});
      await assert.rejects(retrieval.readForRun(pending,{artifactId:sourceArtifact}),/outside/);
      assert.equal(JSON.stringify(capturedResult),serialized);assert.deepEqual(await captured(dispatched.length? (await db.run.findFirstOrThrow({where:{threadId:thread,status:'completed'},orderBy:{createdAt:'asc'}})).id:pending),frozen);
      await chat.cancel(pending);
      const overlapThread=await newThread('Overlapping Topic scope'),first=await newTopic('Shared scope one'),second=await newTopic('Shared scope two');
      await link(overlapThread,[first.id,second.id]);await link(source,[first.id,second.id]);
      const overlap=await send(overlapThread,'Read the earlier literal markers');
      const shared=await retrieval.searchForRun(overlap.id,{query:'%_'});
      assert.equal(shared.topics.length,2);assert.equal(shared.results.length,1);assert.equal(shared.results[0].artifactId,sourceArtifact);
      await link(overlapThread,[second.id]);await link(source,[second.id]);
      await org.change(first.id,{deleted:true,expectedUpdatedAt:first.updatedAt});
      assert.equal((await retrieval.readForRun(overlap.id,{artifactId:sourceArtifact})).results[0].text,capturedResult.results[0].text);
      await org.change(second.id,{deleted:true,expectedUpdatedAt:second.updatedAt});
      await assert.rejects(retrieval.readForRun(overlap.id,{artifactId:sourceArtifact}),/outside/);await chat.cancel(overlap.id);
    });
    await scenarioStep(t,'context-limits',async()=>{
      const longThread=await newThread('Long context');
      await save({scope:'global',key:'response'},'g'.repeat(1000));
      const exact=await send(longThread,'x'.repeat(11000));assert.equal((await captured(exact.id)).messages.reduce((n,x)=>n+modelContentText(x.content).length,0),12000);await chat.cancel(exact.id);
      const count=await db.artifact.count();await assert.rejects(send(longThread,'x'.repeat(11001)),/context limit/);assert.equal(await db.artifact.count(),count);
      await save({scope:'global',key:'response'},'Short guidance');
      const topic=await newTopic('Limits');await link(longThread,[topic.id]);await link(source,[topic.id]);
      const old=await send(source,'old-unique-marker');await chat.cancel(old.id);
      for(let i=0;i<205;i++){const run=await send(source,`scan ${i} 😀 `+'z'.repeat(1010));await chat.cancel(run.id);}
      const current=await send(longThread,'scan');const search=await retrieval.searchForRun(current.id,{query:'scan'});
      assert.equal(search.scanLimited,true);assert.equal(search.truncated,true);assert.ok(search.results.length<=10);assert.ok(search.results.reduce((n,x)=>n+x.text.length,0)<=6000);
      const missing=await retrieval.searchForRun(current.id,{query:'old-unique-marker'});assert.equal(missing.results.length,0);assert.equal(missing.scanLimited,true);
      await chat.cancel(current.id);
      const large=await send(source,'😀'.repeat(3500));await chat.cancel(large.id);
      const next=await send(longThread,'read');const results=await retrieval.searchForRun(next.id,{query:'😀'});const artifactId=results.results[0].artifactId;
      const read=await retrieval.readForRun(next.id,{artifactId,offset:1});assert.equal(read.results[0].offset,0);assert.equal(read.results[0].text.length,4000);assert.equal(read.truncated,true);
      const rest=await retrieval.readForRun(next.id,{artifactId,offset:4000});assert.equal(rest.results[0].text.length,3000);
      const request=await captured(large.id);assert.ok(request.selection.omissions!.history>0);assert.deepEqual(request.selection.omitted,[]);
      await assert.rejects(retrieval.readForRun(next.id,{artifactId,offset:7001}),/exceeds/);await chat.cancel(next.id);
      const many=await Promise.all(Array.from({length:100},(_,i)=>newTopic(`${i} `+'界'.repeat(150))));
      await link(longThread,many.map(x=>x.id));await link(source,many.map(x=>x.id));
      for(let i=0;i<10;i++){const run=await send(source,'escaped '+ '\u0001'.repeat(3990));await chat.cancel(run.id);}
      const bounded=await send(longThread,'Read escaped text');const runtime=topicRuntime(retrieval),signal=new AbortController().signal;
      const identity={runId:bounded.id,threadId:longThread,callId:randomUUID(),signal};
      const context={...identity,authorize:(action:Parameters<typeof runtime.authorize>[0])=>runtime.authorize(action,identity)};
      const prepared=await runtime.tools[0].prepare({query:'escaped'},context);const output=await prepared.execute(context);
      assert.equal(output.status,'success');assert.ok(Buffer.byteLength(JSON.stringify(output))<=32768);assert.ok(output.omissions.includes('Serialized result byte limit reached.'));
      assert.ok(output.references.length>0);await chat.cancel(bounded.id);
    });
    await scenarioStep(t,'context-compatibility',async()=>{
      const run=(await db.run.findFirstOrThrow({where:{threadId:outside,status:'completed'}}));
      const legacyId=randomUUID(),requestId=randomUUID(),now=new Date();
      const legacy=await captured(run.id);delete legacy.selection.topics;delete legacy.selection.omissions;
      legacy.selection.instructions=legacy.selection.instructions.map(({id,key,messageIndex})=>({id,key,messageIndex}));
      // Import an old-format capture; the execution-record guard also protects legacy rows.
      await db.$transaction(async tx=>{
        await tx.run.create({data:{id:legacyId,inputArtifactId:run.inputArtifactId,threadId:outside,retryOfId:run.id,status:'cancelled',requestKey:randomUUID(),requestHash:run.requestHash,state:{request_artifact_id:requestId,response_artifact_id:null},createdAt:now,endedAt:now}});
        await tx.artifact.create({data:{id:requestId,sourceId:run.inputArtifactId,threadId:outside,runId:legacyId,layer:'act',actor:'ash',payload:JSON.parse(JSON.stringify(legacy)),createdAt:now,updatedAt:now}});
      });
      await assert.rejects(db.artifact.update({where:{id:requestId},data:{payload:JSON.parse(JSON.stringify(legacy))}}),/immutable/);
      const retry=await chat.retry(legacyId,randomUUID(),'normal');assert.deepEqual(await captured(retry.id),legacy);await chat.cancel(retry.id);
      const before=await captured(legacyId),membership=await org.readMembership(thread),instructions=await org.readInstruction({scope:'thread',id:thread});
      await stopInstance(ws,instance.id);await startInstance(ws,instance.id,{headless:true});
      assert.deepEqual(await captured(legacyId),before);assert.deepEqual(await org.readMembership(thread),membership);assert.deepEqual(await org.readInstruction(instructions.owner),instructions);
      assert.equal((await api(`artifacts/${requestId}`)).status,200);
    });
  } finally {await chat.stop();await images.stop();await db.$disconnect();await disposeInstance(ws,instance.id);}
});
