import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rename, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { tmpdir } from 'node:os';
import { affectedPlan } from '../../scripts/dev/selection.ts';
import { auditInventory } from '../../scripts/dev/audit-inventory.ts';
import { exec } from '../../scripts/dev/io.ts';
import { impactComponents, scenarios } from '../scenarios.ts';
import ts from 'typescript';
import { fileURLToPath } from 'node:url';
import { exists } from '../../scripts/dev/io.ts';
import { MAX_WORKERS } from '../../scripts/dev/graph.ts';

export async function checkSelection() {
  // Exercise real Git states and source imports. No app services or database needed.
  const source = process.cwd(), checkout = await mkdtemp(join(tmpdir(), 'ash-selection-'));
  const put = async (path: string, text: string) => { await mkdir(dirname(join(checkout, path)), { recursive: true });await writeFile(join(checkout, path), text); };
  const git = (...args: string[]) => exec('git', args, { cwd: checkout });
  const state = join(checkout, 'not-provisioned');
  const cli = (...args:string[]) => exec(process.execPath,['--import',import.meta.resolve('tsx'),fileURLToPath(new URL('../../scripts/dev/verify.ts',import.meta.url)), '--affected','HEAD','--iterate',...args],{cwd:checkout,env:{...process.env,ASH_DEV_ROOT:state}});
  try {
    await git('init', '-q');
    const testFiles = (await exec('git', ['ls-files', '-co', '--exclude-standard', '-z', '--', 'tests'], { cwd: source })).stdout.split('\0').filter(path => /\.(test|spec)\.ts$/.test(path));
    const paths = new Set([...impactComponents.flatMap(c => [...c.files, ...c.consumers]), ...testFiles]);
    for (const path of paths) await put(path, await readFile(join(source, path), 'utf8'));
    await put('package.json',JSON.stringify({scripts:{typecheck:"node -e \"require('node:fs').writeFileSync('unexpected-command','')\""}}));
    await put('pnpm-lock.yaml','lockfileVersion: 9.0\n');
    const dependency = 'packages/server/src/modules/threads/selection-fixture.ts';
    await put(dependency, 'export const fixture = true;');
    await git('add', '.');await git('-c', 'user.name=Ash tests', '-c', 'user.email=tests@localhost', 'commit', '-qm', 'Selection fixture');
    const clean = await affectedPlan(checkout, 'HEAD');
    assert.deepEqual(clean.fallback, []);assert.deepEqual(clean.predictedScenarios, []);
    const route = 'packages/server/src/modules/threads/model-routing.ts';
    const original = await readFile(join(checkout, route), 'utf8');
    await put(route, original + '\n// A routing-only edit\n');
    const focused = await affectedPlan(checkout, 'HEAD');
    assert.deepEqual(focused.fallback, []);
    assert.deepEqual(focused.predictedScenarios.slice().sort(), ['model-routing-execution', 'model-routing-recovery', 'model-routing-desktop'].sort());
    const reference = join(checkout, '.git', 'timing-reference.json');
    const timing = {version:2,passed:true,sourceValid:true,scenarios:[],events:[],commands:[]};
    for (const workers of [1,3,6,MAX_WORKERS]) {
      await writeFile(reference, JSON.stringify({...timing,workers}));
      const estimated = await affectedPlan(checkout, 'HEAD', reference);
      assert.equal(estimated.referenceCost?.workers,workers,'Valid reports at the current and higher worker counts remain usable');
      assert.deepEqual(estimated.predictedScenarios,focused.predictedScenarios);
    }
    await writeFile(reference, JSON.stringify({...timing,workers:MAX_WORKERS+1}));
    await assert.rejects(affectedPlan(checkout,'HEAD',reference),/workers must/);
    const preview=JSON.parse((await cli('--list')).stdout);
    assert.equal(preview.scope,'partial');assert.equal(preview.selection.mode,'iteration');assert.equal(preview.scenarios.length,3);assert.equal(preview.graph.plan.nodes.filter((n:{id:string})=>n.id==='build').length,1);
    assert.equal(await exists(state),false,'Graph preview provisions nothing');
    await put(route, original + "\nimport './selection-fixture.ts';\n");
    assert.ok((await affectedPlan(checkout, 'HEAD')).fallback.some(reason => reason.startsWith('Review new dependency:')));
    await put(route, original);
    const moved = route.replace('model-routing.ts', 'routing-moved.ts');
    await rename(join(checkout, route), join(checkout, moved));
    await git('add', '-A');
    const renamed = await affectedPlan(checkout, 'HEAD');
    assert.ok(renamed.changes.some(c => c.before === route && c.after === moved));
    assert.ok(renamed.fallback.some(reason => reason.startsWith('Stale')));
    assert.equal(renamed.predictedScenarios.length, 0);
    assert.equal(renamed.decision, 'deferred');assert.deepEqual(renamed.iterationScenarios, []);
    await rename(join(checkout, moved), join(checkout, route));await git('add', '-A');
    const consumer = 'packages/server/src/new-consumer.ts';
    await put(consumer, "import {ModelRouting} from './modules/threads/model-routing.ts';");
    const crossFeature = await affectedPlan(checkout, 'HEAD');
    assert.ok(crossFeature.fallback.some(reason => reason.includes('Undeclared model-routing consumer')));
    await rm(join(checkout, consumer));
    const unknown = 'packages/server/src/unknown-feature.ts';await put(unknown, 'export const newFeature = true;');
    assert.ok((await affectedPlan(checkout, 'HEAD')).fallback.some(reason => reason.includes('Unmapped change')));
    await assert.rejects(cli(),(error:any)=>{assert.equal(error.code,2);const result=JSON.parse(error.stdout);assert.equal(result.decision,'deferred');assert.equal(result.passed,null);return true;});
    assert.equal(await exists(state),false,'Deferred selection creates no evidence or environment');assert.equal(await exists(join(checkout,'unexpected-command')),false);
    await rm(join(checkout, unknown));
    const shared = 'packages/shared/src/new-contract.ts';await put(shared, 'export type Contract = string;');
    assert.ok((await affectedPlan(checkout, 'HEAD')).fallback.some(reason => reason.includes('Shared change')));await rm(join(checkout, shared));
    const markdown = 'packages/client/src/renderer/features/threads/markdown.ts';
    const text = await readFile(join(checkout, markdown), 'utf8');await put(markdown, text + '\n// Rendering edit\n');
    const render = await affectedPlan(checkout, 'HEAD');
    assert.deepEqual(render.fallback, []);
    assert.ok(render.direct.some(s => s.id === 'design-reading'));
    assert.deepEqual(render.addedByGroup, []);
    assert.equal(render.predictedScenarios.length, 8);assert.equal(render.expansionRatio, 1);await put(markdown, text);
    const consumerSource = await readFile(join(checkout, impactComponents[0].consumers[0]), 'utf8');
    await put(impactComponents[0].consumers[0], consumerSource.replace("import { ModelRouting, retryRoutingRequest } from './model-routing.ts';", ''));
    assert.ok((await affectedPlan(checkout, 'HEAD')).fallback.some(reason => reason.startsWith('Stale model-routing consumer link:')));
    await put(impactComponents[0].consumers[0], consumerSource);
    await put('docs/note.md', 'Documentation only.');
    assert.deepEqual((await affectedPlan(checkout, 'HEAD')).predictedScenarios, []);
    const unnecessary=JSON.parse((await cli()).stdout);assert.equal(unnecessary.decision,'not-needed');assert.equal(unnecessary.passed,null);assert.equal(await exists(state),false);
    const audit = await auditInventory(checkout);
    assert.equal(audit.located, scenarios.length);assert.deepEqual(audit.errors, []);
    assert.ok(audit.reviewed.every(r => r.current), 'Reviewed similarities stay quiet while their evidence matches');
    const toolPath = 'tests/integration/tools.test.ts', toolSource = await readFile(join(checkout, toolPath), 'utf8');
    await put(toolPath, toolSource.replace('repeat(10000)', 'repeat(10001)'));
    const changedReview = await auditInventory(checkout);
    assert.ok(changedReview.reviewed.some(r => r.scenarios.includes('TOOL-23') && !r.current));
    assert.ok(changedReview.candidates.some(c => c.scenarios.includes('TOOL-23') && c.scenarios.includes('TOOL-06')));
    await put(toolPath, toolSource);
    const chat = 'tests/e2e/chat.spec.ts', chatSource = await readFile(join(checkout, chat), 'utf8');
    const tree = ts.createSourceFile(chat, chatSource, ts.ScriptTarget.Latest, true);
    const body = (id: string) => {
      const statement = tree.statements.find(s => ts.isExpressionStatement(s) && ts.isCallExpression(s.expression) && ts.isStringLiteral(s.expression.arguments[0]) && s.expression.arguments[0].text.startsWith(id + ':')) as ts.ExpressionStatement;
      return ((statement.expression as ts.CallExpression).arguments.find(ts.isArrowFunction) as ts.ArrowFunction).body;
    };
    const originalBody = body('chat-persistence');
    await put(chat, chatSource.slice(0, originalBody.getStart(tree)) + body('chat-layout').getText(tree) + chatSource.slice(originalBody.end));
    const duplicate = await auditInventory(checkout);
    assert.deepEqual(duplicate.errors, []);
    assert.ok(duplicate.candidates.some(c => c.scenarios.includes('chat-persistence') && c.scenarios.includes('chat-layout')), 'Repeated behavior is suggested even across different requirement IDs');
    await put(chat, chatSource + "\ntest('unregistered-scenario: Missing inventory entry', async () => {});\n");
    assert.ok((await auditInventory(checkout)).errors.some(error => error.includes('Unregistered scenario')));
    await put(chat, chatSource.replace('chat-layout:', 'renamed-layout:'));
    const stale = await auditInventory(checkout);
    assert.ok(stale.errors.some(error => error.includes('No executable definition for chat-layout')));
    await assert.rejects(affectedPlan(checkout, '--invalid-ref'));
  } finally { await rm(checkout, { recursive: true, force: true }); }
}
